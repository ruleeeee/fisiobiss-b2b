export function foldGeoName(s) {
  return String(s || "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/region de |region del |region /g, "")
    .replace(/provincia de |comuna de /g, "")
    .replace(/[''`]/g, "")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

export function regionKeyFromApp(name) {
  return foldGeoName(String(name || "").replace(/\s*\([^)]*\)\s*$/, ""));
}

export function comunasForRegion(regionName) {
  return COMUNAS_BY_REGION[regionName] || [];
}

